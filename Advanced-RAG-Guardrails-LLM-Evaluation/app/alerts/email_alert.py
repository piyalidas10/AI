import os
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from datetime import datetime

EMAIL_USER = os.getenv("EMAIL_USER")
EMAIL_PASS = os.getenv("EMAIL_PASS")
ALERT_EMAIL = os.getenv("ALERT_EMAIL")
SMTP_SERVER = os.getenv("SMTP_SERVER", "smtp.gmail.com")
SMTP_PORT = int(os.getenv("SMTP_PORT", 465))

# 🔒 Cooldown (avoid spam)
LAST_EMAIL_TIME = 0
COOLDOWN = 30  # seconds


def should_send_email():
    global LAST_EMAIL_TIME
    now = datetime.now().timestamp()

    if now - LAST_EMAIL_TIME < COOLDOWN:
        return False

    LAST_EMAIL_TIME = now
    return True


def send_email_alert(subject: str, metrics: dict, question: str):

    if not EMAIL_USER or not ALERT_EMAIL:
        return

    if not should_send_email():
        return

    try:
        # 📧 HTML Email Content
        html_content = f"""
        <html>
        <body>
            <h2 style="color:red;">🚨 RAG Guardrails Alert</h2>

            <p><b>Question:</b> {question}</p>

            <h3>⚠️ Issues Detected:</h3>
            <ul>
                <li>Blocked Reason: {metrics.get("blocked_reason")}</li>
                <li>Injection Detected: {metrics.get("injection_detected")}</li>
            </ul>

            <h3>📊 Metrics:</h3>
            <ul>
                <li>Trust Score: {metrics.get("trust_score")}</li>
                <li>Hallucination Score: {metrics.get("hallucination_score")}</li>
                <li>Faithfulness: {metrics.get("faithfulness")}</li>
                <li>Latency: {metrics.get("latency")} sec</li>
            </ul>

            <hr>
            <p style="color:gray;">Generated by RAG Monitoring System</p>
        </body>
        </html>
        """

        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"] = EMAIL_USER
        msg["To"] = ALERT_EMAIL

        msg.attach(MIMEText(html_content, "html"))

        # 🔐 Secure SMTP
        with smtplib.SMTP_SSL(SMTP_SERVER, SMTP_PORT) as server:
            server.login(EMAIL_USER, EMAIL_PASS)
            server.send_message(msg)

        print("✅ Email alert sent")

    except Exception as e:
        print("❌ Email alert failed:", str(e))